/**
 * 源码断言测试专用的「注释剥离」唯一事实源。
 *
 * ⚠️⚠️⚠️ 这个文件的存在本身就是一次事故的产物，先读完再改：
 *
 * 全项目有十几个「读源码文本做断言」的测试（判断某段接线有没有被接上）。
 * 它们每一个都在文件顶部自己抄了一份 stripComments，抄的是同一个有 bug 的版本：
 *
 *     s.replace(/\/*[\s\S]*?\*\//g, "")      // ← 贪心跨行，不认字符串
 *
 * 这个正则不知道自己正站在字符串字面量里。于是源码中任何一个
 * `"image/*"`、`"video/*"`、`"application/*"` 里的 `/*`
 * 都会被当成块注释的开头，一路吞到后面第一个 `*​/` 为止。
 *
 * 实测损伤（2026-09-17 量出来的，不是估的）：
 *   server/index.ts        93851 字符 → 被吃掉 43.6%
 *   admin-store.ts        189291 字符 → 被吃掉 12.7%
 *   InfiniteCanvas.tsx   1211303 字符 → 被吃掉  6.5%
 *
 * 📌⭐⭐⭐ 为什么这比「少测了一点」严重得多：
 * 被吃掉的源码对断言来说是**不存在**的。于是
 *   - 正向断言（toContain）会莫名其妙变红 —— 还算幸运，起码看得见；
 *   - 反向断言（not.toContain）**全部恒绿** —— 你以为它在守门，
 *     其实它连门在哪都没看见。一个恒绿的检测器等于没有检测器。
 *
 * 修法不是把正则写得更花哨（正则永远认不全字符串/模板串/正则字面量），
 * 而是**缩小它的适用范围**：源码断言只关心「代码里写没写某段东西」，
 * 而项目里的块注释一律是独立成行的 JSDoc / 说明块。
 * 所以只剥离「整行都是块注释」的部分，行内出现的 /* 一律不碰。
 * 宁可漏剥一点注释（顶多让断言更严），也绝不能误吃代码（那会让断言失效）。
 */

/**
 * 剥离源码中的注释，用于「读源码文本做断言」的测试。
 *
 * 规则：
 * 1. JSX 注释 `{/* ... *​/}` 剥离。它的行首是 `{` 而不是 `/*`，
 *    只按行首 `/*` 匹配会整段漏掉 —— 实测后果是
 *    CreditsGuidePage 里写在 JSX 注释中的示例数字 85,000
 *    被当成「硬编码」，把一条本来正确的实现判成了违规（假阳性）。
 * 2. 普通块注释只在**独立成行**时剥离（行首允许缩进）。
 *    行内的 `/*` —— 典型是 `"image/*"` 这种 MIME 字符串 —— 保持原样。
 * 3. 行注释 `//` 剥离，但前面是 `:` 的不碰（避免误伤 `https://`）。
 *
 * ⚠️ 顺序不能换：JSX 注释必须先剥，否则第 2 条会把外层的 `{` `}` 留在原地，
 * 留下一堆孤儿花括号，干扰按结构匹配的断言。
 *
 * ⚠️⚠️⚠️ 第 1 条里 `{` 与 `/*` 之间**只允许空格/制表符，不允许换行**。
 * 写成 `\{\s*\/\*` 会顺手匹配到「代码块开头的 `{` 换行后紧跟一段 JSDoc」——
 * 那是普通代码，不是 JSX 注释。实测：在 InfiniteCanvas.tsx 上这样一匹配，
 * 单次就吞掉 171981 个字符（全文件的 14%），接线断言的计数直接归零。
 * 📌 这和本文件开头记的 "image/*" 是同一类错误：**正则的胃口比意图大**。
 *    而且吃错了不报错，只是让断言安静地失效。
 */
export function stripSourceComments(source: string): string {
  return source
    .replace(/\{[ \t]*\/\*[\s\S]*?\*\/[ \t]*\}/g, "")
    .replace(/^[ \t]*\/\*[\s\S]*?\*\/[ \t]*\n?/gm, "")
    .replace(/(^|[^:])\/\/.*$/gm, "$1");
}

/**
 * 剥离后的「没被吃掉」自检。
 *
 * ⚠️ 为什么每个测试文件都该调它一次：
 * stripSourceComments 一旦退化（有人改回贪心正则、或源码里出现新的边界写法），
 * 症状是**静默的**：测试照常跑、照常绿，只是守的门已经不在了。
 * 📌 判据：检测器必须能检测出「自己失效了」，否则它只是个装饰。
 *
 * @param raw     剥离前的原始源码
 * @param stripped 剥离后的结果
 * @param maxLossRatio 允许被剥离掉的最大比例，默认 0.3（注释再多也不该超过三成）
 */
export function assertStripKeptSource(
  raw: string,
  stripped: string,
  maxLossRatio = 0.3,
): void {
  if (raw.length === 0) {
    throw new Error("assertStripKeptSource: 原始源码为空，读文件路径多半写错了");
  }
  const lossRatio = 1 - stripped.length / raw.length;
  if (lossRatio > maxLossRatio) {
    throw new Error(
      `assertStripKeptSource: 注释剥离吃掉了 ${(lossRatio * 100).toFixed(1)}% 的源码` +
        `（上限 ${(maxLossRatio * 100).toFixed(0)}%）。` +
        `这通常意味着源码里出现了 "image/*" 这类含 /* 的字符串，` +
        `把块注释正则带跑了 —— 此时所有 not.toContain 断言都会恒绿。`,
    );
  }
}
