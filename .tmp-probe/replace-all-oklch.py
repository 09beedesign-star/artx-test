# ── 2. 正则替换规则 ────────────────────────────────────────────
# linear-gradient 中的品牌色
REGEX = [
    # 渐变 290 + 200 系列
    (r'linear-gradient\(135deg,\s*oklch\(0\.\d+ 0\.\d+ 290\)[^,]*,\s*oklch\(0\.\d+ 0\.\d+ 200\)[^)]*\)',
     'linear-gradient(135deg, #161616, #333333)'),
    # 任何剩余的 oklch 品牌紫色带透明度 (在非字符串引号上下文)
    (r'oklch\(0\.58 0\.22 290 / 0\.4\)', 'rgba(22,22,22,0.40)'),
    (r'oklch\(0\.58 0\.22 290 / 0\)', 'rgba(22,22,22,0)'),
]

def process_file(path):
    with open(path, 'r', encoding='utf-8') as f:
        original = f.read()
    
    content = original
    for old, new in EXACT:
        content = content.replace(old, new)
    
    for pattern, repl in REGEX:
        content = re.sub(pattern, repl, content)
    
    if content != original:
        with open(path, 'w', encoding='utf-8') as f:
            f.write(content)
        remaining = content.count('oklch')
        changed_count = sum(1 for o, _ in EXACT if o in original)
        return True, remaining
    return False, content.count('oklch')

# ── 3. 遍历所有目标文件 ─────────────────────────────────────────
TARGET_DIRS = [
    'client/src/components/',
    'client/src/pages/',
    'client/src/lib/',
]

total_changed = 0
total_remaining = 0
files_with_remaining = []

for d in TARGET_DIRS:
    for path in sorted(glob.glob(d + '**/*.tsx', recursive=True) + 
                       glob.glob(d + '**/*.ts', recursive=True) +
                       glob.glob(d + '**/*.css', recursive=True)):
        if '.test.' in path:  # 跳过测试文件
            continue
        changed, remaining = process_file(path)
        if changed:
            total_changed += 1
        if remaining > 0:
            files_with_remaining.append((remaining, path))
        total_remaining += remaining

print(f"✅ 修改了 {total_changed} 个文件")
print(f"📊 剩余 oklch 合计: {total_remaining}")
if files_with_remaining:
    print("\n⚠️  仍有残留的文件:")
    for count, path in sorted(files_with_remaining, reverse=True)[:20]:
        print(f"  {count:4d}  {path}")
