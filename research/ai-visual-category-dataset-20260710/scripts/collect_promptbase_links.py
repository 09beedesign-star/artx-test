#!/usr/bin/env python3
"""Collect public PromptBase image prompt links without downloading images."""

from __future__ import annotations

import argparse
import csv
import html
import re
import urllib.request
from pathlib import Path


FIELDS = [
    "group",
    "subcategory",
    "source_site",
    "source_url",
    "image_url",
    "local_image_path",
    "title",
    "public_prompt_or_description",
    "style_prompt_cn",
    "style_prompt_en",
    "likes",
    "views",
    "heat_score",
    "license_note",
    "download_status",
    "notes",
]


def clean(value: str) -> str:
    value = html.unescape(value or "")
    value = re.sub(r"\s+", " ", value).strip()
    return value


def infer_category(title: str) -> tuple[str, str]:
    text = title.lower()
    rules = [
        (("fashion", "tshirt", "hoodie", "embroidery", "patch"), ("行业品类", "服装")),
        (("recipe", "culinary", "food", "restaurant"), ("行业品类", "美食饮品")),
        (("infographic", "whiteboard", "learning", "guide"), ("行业品类", "教育")),
        (("poster", "travel", "editorial"), ("品牌商业", "营销活动")),
        (("character", "storybook", "clipart"), ("人物角色", "AI角色设")),
        (("vintage", "retro"), ("风格美术", "Vintage复古")),
        (("line art", "sketch", "sketchnote", "doodle"), ("图形技法", "铅笔线描")),
    ]
    for keywords, category in rules:
        if any(keyword in text for keyword in keywords):
            return category
    return "其他分类", "其他"


def collect(args: argparse.Namespace) -> int:
    base = Path(args.base)
    source_url = "https://promptbase.com/image-prompts"
    request = urllib.request.Request(source_url, headers={"User-Agent": "Mozilla/5.0 ArtX link collector"})
    page = urllib.request.urlopen(request, timeout=args.timeout).read().decode("utf-8", "ignore")

    pattern = re.compile(
        r'<a[^>]+href="(?P<href>/prompt/[^"]+)"[^>]+title="(?P<link_title>[^"]+)"[^>]*>'
        r'(?:(?!</a>).)*?'
        r'<img[^>]+src="(?P<image>https://assets\.promptbase\.com/[^"]+?500x500\.webp)"[^>]+alt="(?P<alt>[^"]*)"',
        re.S,
    )

    seen: set[str] = set()
    rows: list[dict[str, str]] = []
    for match in pattern.finditer(page):
        if len(rows) >= args.limit:
            break
        image_url = clean(match.group("image"))
        if image_url in seen:
            continue
        seen.add(image_url)
        href = clean(match.group("href"))
        title = clean(match.group("alt")) or clean(match.group("link_title"))
        title = re.sub(r"\s+generated by\s+.+$", "", title, flags=re.I).strip() or clean(match.group("link_title"))
        group, subcategory = infer_category(title)
        rows.append(
            {
                "group": group,
                "subcategory": subcategory,
                "source_site": "PromptBase",
                "source_url": f"https://promptbase.com{href}",
                "image_url": image_url,
                "local_image_path": "",
                "title": title,
                "public_prompt_or_description": title,
                "style_prompt_cn": "",
                "style_prompt_en": title,
                "likes": "",
                "views": "",
                "heat_score": "",
                "license_note": "public preview URL only; prompt marketplace item license must be verified before commercial use",
                "download_status": "link_only",
                "notes": "PromptBase is a supplemental public prompt source, not one of the top-five community sources.",
            }
        )

    with (base / "dataset-links.csv").open("w", encoding="utf-8", newline="") as csv_file:
        writer = csv.DictWriter(csv_file, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(rows)
    print(f"wrote {len(rows)} link rows")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base", default="research/ai-visual-category-dataset-20260710")
    parser.add_argument("--limit", type=int, default=100)
    parser.add_argument("--timeout", type=int, default=30)
    return collect(parser.parse_args())


if __name__ == "__main__":
    raise SystemExit(main())
